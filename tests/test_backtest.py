"""Backtest integrity: look-ahead protection, reporting, and exports."""

from __future__ import annotations

import json

import duckdb
import numpy as np
import pandas as pd
import pytest

from quant_platform.backtest.engine import BacktestEngine
from quant_platform.backtest.strategy import BaseStrategy, RSIStrategy


class _AlwaysBuy(BaseStrategy):
    """Enters on the first bar and never exits."""

    @property
    def name(self) -> str:
        return "always_buy"

    @property
    def required_indicators(self) -> list[str]:
        return ["rsi"]

    def generate_signals(self, data_dict):
        close = data_dict["close"]
        entries = pd.DataFrame(False, index=close.index, columns=close.columns)
        exits = pd.DataFrame(False, index=close.index, columns=close.columns)
        entries.iloc[0] = True
        return entries, exits


@pytest.fixture()
def seeded_db(populated_db):
    """Populate signals with a deterministic RSI-like column."""
    from quant_platform.features.factory import SignalFactory

    SignalFactory().run_pipeline()
    return populated_db


def test_execution_delay_below_one_is_rejected():
    with pytest.raises(ValueError, match="look-ahead"):
        BacktestEngine(RSIStrategy(), execution_delay=0)


def test_signal_is_filled_on_the_next_bar(seeded_db):
    """The fill price must come from bar t+1, not from bar t's close."""
    engine = BacktestEngine(_AlwaysBuy(), execution_delay=1)
    close, indicators = engine.load_data()

    entries, _ = engine.strategy.generate_signals({"close": close, **indicators})
    shifted = entries.shift(1).fillna(False).astype(bool)

    first_true = np.argmax(shifted.to_numpy().any(axis=1))
    assert first_true == 1, "the first executable bar is the one after the signal"
    assert not shifted.iloc[0].any(), "no trade may fill on the signal bar itself"


def test_engine_reports_portfolio_total_not_column_mean(seeded_db):
    results = BacktestEngine(RSIStrategy()).run(init_cash=10_000.0, fee=0.001)
    summary = results["summary"]

    curve = results["equity_curve"]
    assert len(curve) > 0

    # Total capital is preserved: initial value equals the requested cash.
    assert curve[0]["value"] == pytest.approx(10_000.0, rel=1e-9)
    assert summary["initial_cash"] == 10_000.0

    # Final value must match the last point of the exported curve, and the
    # total return must be consistent with it.
    final = curve[-1]["value"]
    assert summary["final_value"] == pytest.approx(final, rel=1e-9)
    assert summary["total_return_pct"] == pytest.approx(
        (final / 10_000.0 - 1.0) * 100.0, rel=1e-9
    )


def test_engine_declares_annualization_basis(seeded_db):
    results = BacktestEngine(RSIStrategy()).run(init_cash=10_000.0)
    assert results["summary"]["annualization_basis_days"] == 252
    assert results["summary"]["execution_delay_bars"] == 1


def test_engine_metrics_are_finite(seeded_db):
    summary = BacktestEngine(RSIStrategy()).run(init_cash=10_000.0)["summary"]
    for key in ("sharpe_ratio", "sortino_ratio", "annualized_return_pct", "max_drawdown_pct"):
        assert np.isfinite(summary[key]), f"{key} must be finite"


def test_win_rate_is_trade_level(seeded_db):
    results = BacktestEngine(RSIStrategy()).run(init_cash=10_000.0)
    trades = results["trades"]
    if not trades:
        pytest.skip("no trades generated by the synthetic series")

    wins = sum(1 for t in trades if t["pnl"] > 0)
    expected = wins / len(trades) * 100.0
    assert results["summary"]["win_rate_pct"] == pytest.approx(expected)


def test_export_writes_valid_json(seeded_db, tmp_path):
    output = tmp_path / "results.json"
    BacktestEngine(RSIStrategy()).run(init_cash=10_000.0, output_path=str(output))

    payload = json.loads(output.read_text())
    assert set(payload) == {"summary", "equity_curve", "trades"}
    assert payload["summary"]["strategy_name"] == "RSI_Strategy_30_70"


